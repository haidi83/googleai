import requests
import streamlit as st
from io import BytesIO
from PIL import Image
from google import genai

client = genai.Client(api_key=st.secrets["GEMINI_API_KEY"])

st.title("What's in this image?")
url = st.text_input("Paste an image URL")

if url:
    try:
        response = requests.get(url, timeout=10)
        image = Image.open(BytesIO(response.content)).convert("RGB")
    except Exception:
        st.error("Couldn't load an image from that URL. Check it's a direct link to a .jpg or .png.")
        st.stop()

    st.image(image)

    result = client.models.generate_content(
        model="gemini-3.5-flash-lite",
        contents=[image, "What is the main thing in this image? Reply with just its name, a few words at most."],
    )
    st.success(result.text)

